--  한 문제씩 채점 (2026-08-08 대표님 지시)
--
--  「답안지를 주지 말고 그냥 바로 문제 풀고 답이 나오게 해」
--  → 한 문제를 내면 그 자리에서 잠그고 정답을 돌려준다.
--
--  ⚠ 답이 새지 않는 이유: **이미 잠긴 문제의 답만** 준다.
--    아직 안 푼 문제의 답은 여전히 안 내려간다.
--  ⚠ 그래서 «몇 판째의 답인가»를 구분해야 한다 — attempt 를 답 기록에 넣는다.
--    없으면 2판째에 같은 문제가 나왔을 때 «이미 답했다»고 잘못 막는다.
-- ════════════════════════════════════════════════════════════════════

ALTER TABLE quiz_answer_log ADD COLUMN attempt INTEGER NOT NULL DEFAULT 1;

-- 한 판에서 같은 문제를 두 번 답할 수 없다 — «틀린 걸 알고 다시 내는» 길을 막는다
CREATE UNIQUE INDEX IF NOT EXISTS uq_qal_once
  ON quiz_answer_log (child_id, ymd, attempt, code);
