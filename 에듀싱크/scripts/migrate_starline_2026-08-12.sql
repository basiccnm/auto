--  실측해 보니 저학년이 그날 할 수 있는 걸 **전부** 해도 15~20 밖에 못 벌었다.
--    의뢰 미션 3개(저학년 평균 별 1.34) = 4 · 세트 보너스 4 · 학교 세트 2
