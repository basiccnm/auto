--  남은 27 은 퀴즈 재도전(코인 3→6→12→24 를 태운다)으로만 채워진다. 코인을 써서 코인을
--  버는 구조라 사실상 안 채워진다. 즉 **60 은 벽이 아니라 안 닿는 천장**이었다.
--
--  그래서 축을 하나로 바꾼다 — 부모는 미션 «개수»가 아니라 **별 예산**을 정한다.
--    · 배정: 그 예산이 찰 때까지 미션을 넣는다 (개수 고정 폐기)
--    · 상한: 하루 상한 = 별 라인 × 1.5  (라인 20 → 상한 30)
--    · 「무조건 통과」 방지: 미션을 하나하나 검사하는 대신 **총량이 라인을 못 넘는다**
