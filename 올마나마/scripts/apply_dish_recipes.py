def main():
    con = sqlite3.connect(DB); con.row_factory = sqlite3.Row; cur = con.cursor()
    cols = [r[1] for r in cur.execute("PRAGMA table_info(dishes)")]
    if "recipe_steps" not in cols:
        cur.execute("ALTER TABLE dishes ADD COLUMN recipe_steps TEXT")
        print("dishes.recipe_steps 컬럼 추가")
    n = miss = 0
    for slug, (serving, steps) in RECIPES.items():
        r = cur.execute("SELECT id, name, serving FROM dishes WHERE slug=?", (slug,)).fetchone()
        if not r:
            print(f"  ⚠️ 요리 없음: {slug}"); miss += 1; continue
        cur.execute("UPDATE dishes SET recipe_steps=?, serving=? WHERE id=?",
                    ("\n".join(steps), serving, r["id"]))
        n += 1
    con.commit()
    print(f"레시피 적용: {n}종" + (f" · 누락 {miss}종" if miss else ""))
    total = cur.execute("SELECT COUNT(*) FROM dishes").fetchone()[0]
    done = cur.execute("SELECT COUNT(*) FROM dishes WHERE recipe_steps IS NOT NULL AND recipe_steps<>''").fetchone()[0]
    print(f"전체 요리 {total}종 중 자체 레시피 보유 {done}종")
    con.close()


if __name__ == "__main__":
    main()
