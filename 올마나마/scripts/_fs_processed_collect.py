def main():
    os.makedirs(OUTDIR, exist_ok=True)
    out = {}
    tree_lines = ["# 식봄 가공/소스/장류/면/유지/통조림 카테고리 트리 (2026-07-25)\n",
                  "구조: 대분류(nid) > 중분류(nid) > 잎(nid) · 총건수/파싱건수\n"]
    n_req = 0
    stop = False
    for root_nid, (root_name, mids) in TREE.items():
        tree_lines.append("\n## %s (nid %d)\n" % (root_name, root_nid))
        for mid_nid, (mid_name, leaves) in mids.items():
            tree_lines.append("- **%s** (nid %d)\n" % (mid_name, mid_nid))
            for leaf_nid, leaf_name in leaves.items():
                label = "%s>%s" % (mid_name, leaf_name)
                try:
                    total, rows = fc.cat_search(leaf_nid)
                    n_req += 1
                except urllib.error.HTTPError as e:
                    print("  !! %s(nid %d) HTTP %s — 중단" % (label, leaf_nid, e.code))
                    stop = True; break
                except Exception as e:
                    print("  !! %s(nid %d) %s" % (label, leaf_nid, e))
                    tree_lines.append("    - %s (nid %d) · ERROR\n" % (leaf_name, leaf_nid))
                    time.sleep(GAP); continue
                out[label] = rows
                priced = [r for r in rows if r["won_per_kg"]]
                tree_lines.append("    - %s (nid %d) · 총%d·파싱%d\n" % (
                    leaf_name, leaf_nid, total, len(priced)))
                print("%-40s(nid %3d) 총%4d·파싱%3d" % (label, leaf_nid, total, len(priced)),
                      flush=True)
                time.sleep(GAP)
            if stop:
                break
        if stop:
            break

    with open(os.path.join(OUTDIR, "_가공카테고리.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    with open(os.path.join(OUTDIR, "_가공카테고리_트리.md"), "w", encoding="utf-8") as f:
        f.writelines(tree_lines)
    print("\n요청 %d건 · 잎 %d개 수집" % (n_req, len(out)))
    print("→ data/research/foodspring/_가공카테고리.json")
    print("→ data/research/foodspring/_가공카테고리_트리.md")
    if stop:
        print("!! 차단 징후로 중단됨 — 부분 저장")


if __name__ == "__main__":
    main()
