# ⚠️ 시판 소스·양념·드레싱은 재료명에 '베이컨/닭/돼지'가 들어가도 **가공품**이다
#    (베이컨앤크림소스·닭갈비양념·탕수육소스). 이걸 먼저 걸러야 축산에 소스가 안 섞인다.
