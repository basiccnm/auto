# 화면 표기용 (한글 → 아이콘 클래스·글자)
CLS = {"축산": ("chuk", "축"), "수산": ("su", "수"), "농산": ("nong", "농"), "가공": ("ga", "가")}


def cat_of(key, name, klass, is_retail=0):
    """재료를 축산/수산/농산/가공 중 하나로. name=재료명, klass=ingredients.class, is_retail=시판여부."""
    if key in ("vegetables_fresh", "salad_greens", "rice_uncooked"):
        return "농산"
    if is_retail or any(w in name for w in _PROC):
        return "가공"
    if any(w in name for w in _FISH):
        return "수산"
    if any(w in name for w in _MEAT):
        return "축산"
    if klass == "농축산물" or any(w in name for w in _GRAIN_VEG):
        return "농산"
    return "가공"


def cls4(key, name, klass, is_retail=0):
    """cat_of 를 (아이콘클래스, 한글자)로. 메뉴 페이지 재료 아이콘용."""
    return CLS[cat_of(key, name, klass, is_retail)]
