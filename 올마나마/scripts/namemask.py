    for t in ("냄비에 물 400ml와 곰곰 떡볶이 양념 80g을 푸세요",
              "[로켓프레시] 곰곰 매콤 제육 + 땡초어묵 (냉동)",
              "해찬들 고기전용 쌈장, 쌈채소, 치킨무와 함께 내세요",
              "물을 붓고 CJ 다담 김치찌개 양념 20g을 푸세요",
              "뫼루니식품 바사삭 닭강정파우더, 5kg, 1개",
              "백설탕 100g을 넣으세요",
              "오뚜기 오리엔탈 드레싱을 뿌려 내세요"):
        print("  %-52s → %s" % (t[:52], mask(t)))
