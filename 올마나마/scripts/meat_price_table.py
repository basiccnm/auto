def cutmin(nids, sp):
    lo, hi = PLAUS[sp]; blk = BLOCK[sp]
    cand = []
    for nid in nids:
        for r in c.get(str(nid), {}).get("rows", []):
            w = r.get("won_per_kg"); nm = r["name"]
            if not w or not r.get("pack_kg") or r["pack_kg"] < 1: continue
            if BAD.search(nm) or blk.search(nm) or not (lo <= w <= hi): continue
            cand.append(w)
    if not cand: return None
    cand.sort(); med = cand[len(cand) // 2]
    cand = [w for w in cand if med * 0.4 <= w <= med * 2.5]
    return min(cand) if cand else None


def table(title, cuts, sp, origins):
    print("\n=== %s (원/kg, 원산지별 최저) ===" % title)
    print("%-8s " % "부위" + " ".join("%9s" % o for o in origins))
    print("-" * (9 + 10 * len(origins)))
    for cut, om in cuts.items():
        cells = []
        for o in origins:
            v = cutmin(om.get(o, []), sp)
            cells.append(f"{v:,}" if v else "-")
        print("%-8s " % cut + " ".join("%9s" % x for x in cells))


